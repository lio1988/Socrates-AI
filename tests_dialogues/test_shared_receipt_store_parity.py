def _consult_receipt(variant="v", request_id=_RID):
    req = ExternalConsultationRequest(
        request_id=request_id, requesting_agent_id="a",
        mode="independent_solver", consulted_provider="mock",
        consulted_model="m", consultation_relation="peer_model",
        question="q " + variant, purpose="p", max_tokens=64,
        timeout_seconds=5.0, created_at=_NOW, expires_at=_EXP)
    svc = ExternalConsultationService(ConsultationPolicy(), worker_id="w",
                                      clock=lambda: _NOW)
    return asyncio.run(svc.consult(req, MockConsultationProvider("mock"),
                                   now=_NOW)).receipt


