# --------------------------------------------------------------------------- #
# mixed primary/fallback concurrency through the KERNEL wrapper
# --------------------------------------------------------------------------- #

def _run_kernel_gated_mixed_race(
        store, winner_receipt, loser_receipt, *, winner_role, monkeypatch):
    loser_role = "primary" if winner_role == "fallback" else "fallback"
    real_open = core_mod.os.open
    real_link = core_mod.os.link
    real_replace = core_mod.os.replace
    thread_role = threading.local()
    winner_has_lock = threading.Event()
    loser_attempted_lock = threading.Event()
    counter_lock = threading.Lock()
    counters = {
        "capability": {"primary": 0, "fallback": 0},
        "lock": {"primary": 0, "fallback": 0},
        "link": {"primary": 0, "fallback": 0},
        "replace": {"primary": 0, "fallback": 0},
    }

    def bump(operation, role):
        with counter_lock:
            counters[operation][role] += 1

    def tracked_open(name, flags, *args):
        role = thread_role.value
        bump("lock", role)
        try:
            fd = real_open(name, flags, *args)
        except (FileExistsError, PermissionError):
            if role == loser_role and winner_has_lock.is_set():
                loser_attempted_lock.set()
            raise
        if role == winner_role:
            winner_has_lock.set()
        return fd

    def mixed_link(src, dst):
        role = thread_role.value
        bump("link", role)
        if role == "fallback":
            raise OSError("forced fallback capability")
        if role == winner_role and not loser_attempted_lock.wait(timeout=5):
            raise RuntimeError("loser never attempted the shared lock")
        return real_link(src, dst)

    def gated_replace(src, dst):
        role = thread_role.value
        bump("replace", role)
        if role == winner_role and not loser_attempted_lock.wait(timeout=5):
            raise RuntimeError("loser never attempted the shared lock")
        return real_replace(src, dst)

    monkeypatch.setattr(core_mod.os, "open", tracked_open)
    monkeypatch.setattr(core_mod.os, "link", mixed_link)
    monkeypatch.setattr(core_mod.os, "replace", gated_replace)
    results = {}

    def worker(label, role, receipt):
        thread_role.value = role
        bump("capability", role)
        try:
            store.save(receipt)
            results[label] = "WIN"
        except MicroSocraticError:
            results[label] = "CONFLICT"
        except Exception as exc:                        # noqa: BLE001
            results[label] = f"ERR:{type(exc).__name__}"

    winner = threading.Thread(
        target=worker,
        args=("winner", winner_role, winner_receipt),
        name=f"kernel-{winner_role}-winner",
    )
    loser = threading.Thread(
        target=worker,
        args=("loser", loser_role, loser_receipt),
        name=f"kernel-{loser_role}-loser",
    )
    winner.start()
    assert winner_has_lock.wait(timeout=5)
    loser.start()
    winner.join(timeout=10)
    loser.join(timeout=10)
    assert not winner.is_alive() and not loser.is_alive()
    assert loser_attempted_lock.is_set()
    assert counters["capability"] == {"primary": 1, "fallback": 1}
    assert counters["lock"][winner_role] == 1
    assert counters["lock"][loser_role] >= 1
    assert counters["link"][winner_role] == 1
    assert counters["link"][loser_role] == 0
    if winner_role == "fallback":
        assert counters["replace"] == {"primary": 0, "fallback": 1}
    else:
        assert counters["replace"] == {"primary": 0, "fallback": 0}
    return results, counters


