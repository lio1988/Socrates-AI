def test_error_types_do_not_cross_domains(tmp_path):
    c = ConsultationReceiptStore(tmp_path / "c")
    k = MicroSocraticReceiptStore(tmp_path / "k")
    # consultation conflict -> ConsultationError, never MicroSocraticError
    c.save(_consult_receipt("A"))
    with pytest.raises(ConsultationError):
        c.save(_consult_receipt("B"))
    # kernel conflict -> MicroSocraticError, never ConsultationError
    k.save(_kernel_receipt("A"))
    with pytest.raises(MicroSocraticError):
        k.save(_kernel_receipt("B"))
    # cross-check: neither raise is the other domain's error class
    assert not issubclass(ConsultationError, MicroSocraticError)
    assert not issubclass(MicroSocraticError, ConsultationError)


