_FIXED_TEMP_HEX = "0123456789abcdef0123456789abcdef"


class _FaultingTempHandle:
    """Real exclusive temp handle with one injected post-create failure."""

    def __init__(self, handle, state, *, fail_write=False, fail_close=False):
        self._handle = handle
        self._state = state
        self._fail_write = fail_write
        self._fail_close = fail_close

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, traceback):
        self.close()
        return False

    def __getattr__(self, name):
        return getattr(self._handle, name)

    def write(self, payload):
        self._state["write_attempts"] += 1
        if self._fail_write:
            raise OSError(5, "simulated sensitive filesystem detail")
        return self._handle.write(payload)

    def flush(self):
        self._state["flush_attempts"] += 1
        return self._handle.flush()

    def close(self):
        self._state["close_attempts"] += 1
        self._handle.close()  # close the real descriptor before reporting error
        if self._fail_close:
            raise OSError(5, "simulated sensitive filesystem detail")


def _install_temp_fault(monkeypatch, *, fail_write=False, fail_close=False):
    real_open = builtins.open
    state = {
        "write_attempts": 0,
        "flush_attempts": 0,
        "close_attempts": 0,
        "raw_handles": [],
    }

    class _FixedUUID:
        hex = _FIXED_TEMP_HEX

    def faulting_open(file, mode="r", *args, **kwargs):
        handle = real_open(file, mode, *args, **kwargs)
        if mode == "x" and os.fspath(file).endswith(".receipt.tmp"):
            state["raw_handles"].append(handle)
            return _FaultingTempHandle(
                handle, state, fail_write=fail_write, fail_close=fail_close)
        return handle

    monkeypatch.setattr(core_mod.uuid, "uuid4", lambda: _FixedUUID())
    monkeypatch.setattr(builtins, "open", faulting_open)
    return state, f".{_FIXED_TEMP_HEX}.receipt.tmp"


def _trace_save_deadline(monkeypatch, store):
    seen = {"acquire": [], "reconcile": []}
    real_acquire = store._acquire_lock
    real_reconcile = store._reconcile

    def traced_acquire(lock, path, deadline):
        seen["acquire"].append(deadline)
        return real_acquire(lock, path, deadline)

    def traced_reconcile(path, verified, *, deadline=None):
        seen["reconcile"].append(deadline)
        return real_reconcile(path, verified, deadline=deadline)

    monkeypatch.setattr(store, "_acquire_lock", traced_acquire)
    monkeypatch.setattr(store, "_reconcile", traced_reconcile)
    return seen


