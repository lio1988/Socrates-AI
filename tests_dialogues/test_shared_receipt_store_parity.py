def _mixed_race(store, receipts):
    real_link = core_mod.os.link
    tl = threading.local()
    capability_lock = threading.Lock()
    capabilities = []

    def link(src, dst):
        if getattr(tl, "fallback", False):
            raise OSError("forced fallback")
        return real_link(src, dst)

    barrier = threading.Barrier(len(receipts))
    wins, conflicts, leaks = [], [], []

    def worker(i):
        role = "fallback" if i % 2 == 0 else "primary"
        tl.fallback = role == "fallback"
        with capability_lock:
            capabilities.append(role)
        barrier.wait()
        try:
            store.save(receipts[i]); wins.append(receipts[i]["receipt_digest"])
        except MicroSocraticError:
            conflicts.append(1)
        except Exception as exc:                        # noqa: BLE001
            leaks.append(type(exc).__name__)

    original = core_mod.os.link
    core_mod.os.link = link
    try:
        with ThreadPoolExecutor(max_workers=len(receipts)) as pool:
            list(pool.map(worker, range(len(receipts))))
    finally:
        core_mod.os.link = original
    return wins, conflicts, leaks, capabilities


def test_kernel_mixed_conflicting_stress(tmp_path):
    receipts = [_kernel_receipt(f"distinct {i}") for i in range(8)]
    for trial in range(10):
        trial_dir = tmp_path / f"kc-{trial}"
        store = MicroSocraticReceiptStore(trial_dir)
        wins, conflicts, leaks, capabilities = _mixed_race(store, receipts)
        assert leaks == []
        assert len(wins) == 1 and len(conflicts) == 7   # kernel error type
        assert capabilities.count("primary") == 4
        assert capabilities.count("fallback") == 4
        stored = MicroSocraticReceiptStore(trial_dir).load(_RID)
        assert verify_kernel_receipt(stored)["receipt_digest"] == wins[0]
        assert _no_artifacts(trial_dir) == [_hashed()]


